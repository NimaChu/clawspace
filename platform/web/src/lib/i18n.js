export function detectLocale(request) {
  const cookieHeader = request?.headers?.get?.('cookie') || '';
  const matchedCookie = cookieHeader.match(/(?:^|;\s*)nima_locale=(zh|en)(?:;|$)/i);
  if (matchedCookie?.[1]) {
    return matchedCookie[1].toLowerCase();
  }

  const header = request?.headers?.get?.('accept-language') || '';
  return /\bzh\b/i.test(header) ? 'zh' : 'en';
}

export function getTranslationsForLocale(locale) {
  return locale === 'zh' || locale === 'zh-CN' ? ZH : EN;
}

export function getTranslations(request) {
  const locale = detectLocale(request);
  return getTranslationsForLocale(locale);
}
